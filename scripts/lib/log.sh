#!/usr/bin/env bash

# Назначение:
#   Единая диагностика установщиков dotfiles в stderr.
#
# Использование:
#   source scripts/lib/log.sh после set -Eeuo pipefail.
#
# Параметры:
#   Это библиотека; позиционных параметров нет.
#
# Окружение:
#   Специальных переменных нет.
#
# Функции:
#   dotfiles_log <сообщение> — сообщение с именем скрипта и текущим этапом;
#   dotfiles_stage <название> — сменить этап и вывести заголовок;
#   dotfiles_report_error <код> <строка> — обработчик ERR, завершает с тем же
#   кодом.
#
# Результат:
#   Ошибка содержит этап, строку и исходный код; stdout остаётся свободен для
#   вывода команд. Команды/окружение не печатаются, чтобы не раскрыть секреты.
#   ERR не перехватывает проверки в if/! и явный exit: их причины сообщает
#   вызывающий скрипт. EXIT-trap для удаления временных файлов остаётся в
#   ведении вызывающего кода.

dotfiles_current_stage='подготовка'

# Все аргументы объединяются в одно сообщение; printf не трактует их как формат.
dotfiles_log() {
    printf '[%s][%s] %s\n' "${0##*/}" "$dotfiles_current_stage" "$*" >&2
}

# Один аргумент — понятное имя этапа, которое попадёт и в сообщение об ошибке.
dotfiles_stage() {
    dotfiles_current_stage="$1"
    printf '[%s][%s]\n' "${0##*/}" "$dotfiles_current_stage" >&2
}

# Сначала сохраняем исходный код: диагностический printf не должен его подменить.
dotfiles_report_error() {
    local status="$1" line="$2"
    dotfiles_log "Ошибка на строке $line, код $status. Причина команды — в выводе выше; выполнение остановлено."
    exit "$status"
}

trap 'dotfiles_report_error "$?" "$LINENO"' ERR
